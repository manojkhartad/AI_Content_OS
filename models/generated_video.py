# ==========================================================
# Imports
# ==========================================================

from dataclasses import dataclass


# ==========================================================
# Generated Video
# ==========================================================

@dataclass
class GeneratedVideo:

    # ------------------------------------------------------
    # Story Information
    # ------------------------------------------------------

    title: str

    # ------------------------------------------------------
    # Output Files
    # ------------------------------------------------------

    video_path: str

    thumbnail_path: str = ""

    subtitle_path: str = ""

    # ------------------------------------------------------
    # Resolution
    # ------------------------------------------------------

    width: int = 1024

    height: int = 576

    fps: int = 30

    # ------------------------------------------------------
    # Duration
    # ------------------------------------------------------

    duration: float = 0.0

    # ------------------------------------------------------
    # Encoding
    # ------------------------------------------------------

    codec: str = "H.264"

    format: str = "MP4"

    # ------------------------------------------------------
    # Provider
    # ------------------------------------------------------

    provider: str = "FFmpeg"

    # ------------------------------------------------------
    # Status
    # ------------------------------------------------------

    total_scenes: int = 0

    status: str = "completed"